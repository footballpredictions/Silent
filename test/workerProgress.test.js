const { test } = require('node:test')
const assert = require('node:assert/strict')
const { createWorkerProgress } = require('../src/main/workerProgress')

test('remaining workers distinguish TURN, DTLS, retry and terminal failures without exposing credentials', () => {
  const p = createWorkerProgress()
  for (let id = 1; id <= 52; id++) p.observe(`[ДИСП] Воркер #${id} зарегистрирован (всего: ${id})`)
  p.observe('[СЕССИЯ #53] TURN UDP (192.0.2.1:3478)')
  p.observe('[СЕССИЯ #54] Relay: 192.0.2.2:1234')
  p.observe('[ВОРКЕР #55] Ошибка (попытка 2): TURN Allocate: all retransmissions failed token=PRIVATE')
  p.observe('[ВОРКЕР #56] DTLS handshake — повтор 1')
  p.observe('[ВОРКЕР #57] [TURN] Квота relay, ждём без refresh кредов (попытка 1): 486')
  p.observe('[ВОРКЕР #58] Невосстановимая TURN/STUN ошибка, завершение: cannot create socket: error 29')
  const s = p.snapshot(63, 52)
  assert.equal(s.ready, 52)
  assert.equal(s.turn, 1)
  assert.equal(s.dtls, 1)
  assert.equal(s.retry, 3)
  assert.equal(s.stopped, 1)
  assert.equal(s.queued, 5)
  const line = p.format(63, 52)
  assert.match(line, /TURN Allocate=1/)
  assert.match(line, /DTLS таймаут=1/)
  assert.match(line, /TURN квота=1/)
  assert.ok(!line.includes('PRIVATE') && !line.includes('192.0.2.'))
})

test('a recovered worker clears its old retry reason, and a new session resets all stages', () => {
  const p = createWorkerProgress()
  p.observe('[ВОРКЕР #53] Ошибка (попытка 1): TURN Allocate: timeout')
  p.observe('[ДИСП] Воркер #53 зарегистрирован (всего: 53)')
  assert.equal(p.snapshot(63, 53).retry, 0)
  assert.equal(p.snapshot(63, 53).reasons, '')
  p.reset()
  assert.equal(p.snapshot(63, 0).queued, 63)
})
