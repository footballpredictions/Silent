_BY_KIND: dict[str, BlockMethod] = {m.kind: m for m in _METHODS}


def method(kind: str) -> BlockMethod:
    return _BY_KIND.get(kind, _BY_KIND[KIND_UNKNOWN])


def all_methods() -> tuple[BlockMethod, ...]:
    return _METHODS


def knowledge_to_dict() -> list[dict]:
    """Справочник для админки: методы, признаки и решения."""
    return [
        {
            "kind": m.kind,
            "title": m.title,
            "severity": m.severity,
            "how_it_works": m.how_it_works,
            "signals": list(m.signals),
            "fixes": list(m.fixes),
            "commands": list(m.commands),
        }
        for m in _METHODS
    ]


def render_commands(kind: str, *, host: str = "", domain: str = "", port: int = 0) -> list[str]:
    """Подставить в шаблоны команд конкретные IP/домен/порт."""
    out: list[str] = []
    for cmd in method(kind).commands:
        text = cmd
        if host:
            text = text.replace("<IP>", host)
        if domain:
            text = text.replace("<домен>", domain)
        elif host:
            text = text.replace("<домен>", host)
        if port:
            text = text.replace("<PORT>", str(port))
        out.append(text)
    return out
