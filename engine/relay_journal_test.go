package main

import "testing"

func TestRelayJournalOnlyPublishesStructuredEvents(t *testing.T) {
	for _, tc := range []struct {
		raw, message string
		level        int
	}{
		{"[ГРУППА #1] Запрос кредов (хеш: confidential...)", "", 0},
		{"[STREAM 100] VK token=confidential", "", 0},
		{"[ГРУППА #1] Креды OK, TURN: [turn:192.0.2.1], 3 воркеров", "[VK] Параметры TURN получены", 1},
		{"[СЕССИЯ #2] Relay: 192.0.2.1:5432", "[TURN] Канал выделен", 1},
		{"[ВОРКЕР #2] [DTLS] Соединение установлено ✓", "[DTLS] Соединение установлено ✓", 1},
		{"[ВОРКЕР #2] Конфиг получен", "[ВОРКЕР #2] Конфиг получен", 1},
		{"[ВОРКЕР #63] [READY] Туннель готов к работе ✓", "[READY] Канал готов ✓", 1},
		{"[ВОРКЕР #2] Ошибка конфига: private-key=confidential", "Воркер №2 · GETCONF: настройки не получены", 2},
		{"[ВОРКЕР #2] [TURN] Квота relay, ждём без refresh кредов (попытка 1): confidential", "Воркер №2 · TURN: квота каналов, ожидаем повтор", 2},
		{"[ДИСП] Воркер #2 зарегистрирован (всего: 3)", "Воркер №2 активен · активных каналов: 3", 0},
		{"[ДИСП] Воркер #2 отключён (осталось: 1)", "Воркер №2 отключён · активных каналов: 1", 0},
		{"[СТАТИСТИКА] Активных: 3 | Трафик: 0.29 МБ", "[СТАТИСТИКА] Активных: 3 | Трафик: 0.29 МБ", 0},
		{"[ВОРКЕР #2] Keepalive: запись не прошла, канал закрывается", "Воркер №2 · DTLS: ошибка keepalive, канал закрывается", 2},
		{"[ВОРКЕР #2] Access-check: запись не прошла, канал закрывается", "Воркер №2 · DTLS: ошибка проверки доступа, канал закрывается", 2},
		{"[ВОРКЕР #2] TURN: продление allocation не подтверждено, канал закрывается", "Воркер №2 · TURN: ошибка продления канала", 2},
		{"[ВОРКЕР #2] TURN: продление permission не подтверждено, канал закрывается", "Воркер №2 · TURN: ошибка продления разрешения", 2},
		{"[ВОРКЕР #2] TURN: продление allocation не подтверждено, канал закрывается · код 437", "Воркер №2 · TURN: ошибка продления канала · код 437", 2},
		{"[ВОРКЕР #2] TURN: продление permission не подтверждено, канал закрывается · таймаут", "Воркер №2 · TURN: ошибка продления разрешения · таймаут", 2},
		{"[ВОРКЕР #2] TURN: NAT изменился, старый канал недействителен", "Воркер №2 · сеть: NAT изменился, канал обновляется", 0},
		{"[ВОРКЕР #2] TURN: физическая сеть изменилась, нужен новый сокет", "Воркер №2 · сеть: обновляем UDP-сокет после смены интерфейса", 0},
		{"[ВОРКЕР #2] TURN: канал не отвечает на повторную проверку после потери сети", "Воркер №2 · TURN: нет ответа на две проверки · обновляем недоступный канал", 2},
		{"[ВОРКЕР #2] Ошибка Reader: EOF", "Воркер №2 · DTLS: ретранслятор закрыл соединение (EOF)", 2},
		{"[ВОРКЕР #2] Ошибка Reader: read udp 192.0.2.1:1234: network is unreachable", "Воркер №2 · DTLS: сеть недоступна при чтении", 2},
		{"[ВОРКЕР #2] Ошибка Writer: write udp 192.0.2.1:1234: i/o timeout", "Воркер №2 · DTLS: таймаут записи", 2},
		{"[ВОРКЕР #2] Ошибка Reader: confidential-key=do-not-export", "Воркер №2 · DTLS: ошибка чтения канала", 2},
	} {
		message, level := relayJournalEvent("2026/11/13 16:45:21 " + tc.raw + "\n")
		if message != tc.message || level != tc.level {
			t.Errorf("got (%q, %d), want (%q, %d)", message, level, tc.message, tc.level)
		}
	}
}
